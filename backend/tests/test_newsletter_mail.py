# --- Configuration guards --------------------------------------------------


def _settings(**overrides: object) -> Settings:
    base: dict[str, object] = {
        "_env_file": None,
        "SUPABASE_JWT_SECRET": "x" * 40,
    }
    return Settings(**{**base, **overrides})  # type: ignore[arg-type]


def test_console_transport_is_refused_in_production() -> None:
    """It writes single-use confirmation links to the log, and a production
    log outlives the 24 hours those links are meant to."""
    with pytest.raises(ValidationError, match="console"):
        _settings(ENVIRONMENT="production", MAIL_PROVIDER="console")


def test_disabled_transport_is_allowed_in_production() -> None:
    """Silence is a defensible production state — it is what the code did
    before this transport existed."""
    assert _settings(ENVIRONMENT="production", MAIL_PROVIDER="disabled").MAIL_PROVIDER == "disabled"


def test_brevo_without_a_key_fails_at_startup_not_at_the_first_subscriber() -> None:
    with pytest.raises(ValidationError, match="BREVO_API_KEY"):
        _settings(MAIL_PROVIDER="brevo", BREVO_API_KEY="")


def test_brevo_with_a_key_is_accepted() -> None:
    assert _settings(MAIL_PROVIDER="brevo", BREVO_API_KEY="k").MAIL_PROVIDER == "brevo"


def test_site_url_trailing_slash_is_normalised() -> None:
    """Or every link builder concatenates its way to a double slash, which
    some mail scanners rewrite and some proxies reject."""
    assert _settings(SITE_URL="https://x.test/").SITE_URL == "https://x.test"
